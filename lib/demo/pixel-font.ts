/** Width in px of `text` at pixel size `px` (5 columns + 1 gap per glyph). */
export function pixelTextWidth(text: string, px: number): number {
  return Math.max(0, text.length * 6 - 1) * px;
}

/**
 * SVG <rect>s spelling `text` (upper-cased; unknown characters become spaces),
 * with its top-left corner at (x, y). Runs of pixels in a row merge into one rect.
 */
export function pixelText(text: string, x: number, y: number, px: number, fill: string): string {
  const rects: string[] = [];
  [...text.toUpperCase()].forEach((ch, i) => {
    const glyph = GLYPHS[ch] ?? GLYPHS[" "]!;
    glyph.forEach((row, r) => {
      let c = 0;
      while (c < row.length) {
        if (row[c] !== "#") {
          c++;
          continue;
        }
        let end = c;
        while (end < row.length && row[end] === "#") end++;
        rects.push(`<rect x="${x + (i * 6 + c) * px}" y="${y + r * px}" width="${(end - c) * px}" height="${px}"/>`);
        c = end;
      }
    });
  });
  return `<g fill="${fill}">${rects.join("")}</g>`;
}
